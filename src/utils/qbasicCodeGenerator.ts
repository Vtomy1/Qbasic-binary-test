import { ConversionResult, HeaderMode } from '../types/qbasic';

export interface CodeGeneratorOptions {
  filename: string;
  result: ConversionResult;
}

export function generateQBasicLoaderCode(options: CodeGeneratorOptions): string {
  const { filename, result } = options;
  const { width, height, bitDepth, headerMode } = result;

  const fn = filename.toUpperCase().endsWith('.BIN') ? filename.toUpperCase() : `${filename.toUpperCase()}.BIN`;

  // BSAVE mode has a simple 5-line loader
  if (headerMode === 'dos-bsave' && bitDepth === 8) {
    return `' ===============================================================
' QBasic 1.1 / QuickBASIC 4.5 - Fast BLOAD Screen 13 Image Loader
' Compatible with DOSBox, genuine MS-DOS, and FreeDOS
' Generated by QBasic Binary Image Studio
' ===============================================================
DEFINT A-Z
SCREEN 13                   ' 320x200 256 colors mode

PRINT "Loading ${fn}..."

' Set memory segment to VGA display memory (&HA000:0000)
DEF SEG = &HA000
BLOAD "${fn}", 0            ' Directly blits into video RAM!
DEF SEG                     ' Restore default memory segment

LOCATE 1, 1: PRINT "Press any key to exit...";
WHILE INKEY$ = "": WEND
SCREEN 0: WIDTH 80: CLS
END
`;
  }

  // PUT Array Mode
  if (headerMode === 'qb-put') {
    const arrayElements = Math.ceil(result.fileSizeBytes / 2) + 10;
    let screenMode = 'SCREEN 13';
    if (bitDepth === 4) screenMode = 'SCREEN 7';
    if (bitDepth === 2) screenMode = 'SCREEN 1';
    if (bitDepth === 1) screenMode = 'SCREEN 11';

    return `' ===============================================================
' QBasic 1.1 / QuickBASIC 4.5 - Binary PUT Array Image Loader
' Format: QBasic GET/PUT array buffer
' Image: ${width}x${height}, ${bitDepth}-bit color depth
' ===============================================================
DEFINT A-Z
${screenMode}
CLS

DIM imgBuffer%(${arrayElements})

OPEN "${fn}" FOR BINARY AS #1
FOR i% = 0 TO ${Math.ceil(result.fileSizeBytes / 2)}
    GET #1, , imgBuffer%(i%)
NEXT i%
CLOSE #1

' Blit image at coordinates (X, Y) using PUT
PUT (10, 10), imgBuffer%, PSET

LOCATE 1, 1: PRINT "PUT blit complete. Press any key...";
WHILE INKEY$ = "": WEND
SCREEN 0: WIDTH 80: CLS
END
`;
  }

  // 1-Bit Loader
  if (bitDepth === 1) {
    const bytesPerLine = Math.ceil(width / 8);
    return `' ===============================================================
' QBasic 1.1 / QuickBASIC 4.5 - 1-Bit Binary Image Loader
' Image: ${width}x${height} Monochrome (8 pixels per byte)
' Header Mode: ${headerMode.toUpperCase()}
' ===============================================================
DEFINT A-Z
SCREEN 11                   ' 640x480 Monochrome (or SCREEN 2 for 640x200)
CLS

fileName$ = "${fn}"
fileNum% = FREEFILE

OPEN fileName$ FOR BINARY AS #fileNum%

${headerMode === 'qb-header' ? `' Read 8-byte structured header
magic$ = SPACE$(2)
GET #fileNum%, , magic$
IF magic$ <> "QB" THEN
    PRINT "Invalid file signature!"
    CLOSE #fileNum%: END
END IF
GET #fileNum%, , imgWidth%
GET #fileNum%, , imgHeight%
GET #fileNum%, , bpp$
GET #fileNum%, , flags$
` : ''}imgW% = ${width}
imgH% = ${height}
bytesPerLine% = ${bytesPerLine}

PRINT "Decoding ${width}x${height} 1-bit stream..."

rawByte$ = " "

FOR y% = 0 TO imgH% - 1
    FOR bIdx% = 0 TO bytesPerLine% - 1
        GET #fileNum%, , rawByte$
        byteVal% = ASC(rawByte$)

        ' Unpack 8 pixels from high bit (MSB) to low bit (LSB)
        FOR bitPos% = 7 TO 0 STEP -1
            x% = bIdx% * 8 + (7 - bitPos%)
            IF x% < imgW% THEN
                IF (byteVal% AND (2 ^ bitPos%)) <> 0 THEN
                    PSET (x%, y%), 15   ' Bright White
                ELSE
                    PSET (x%, y%), 0    ' Black
                END IF
            END IF
        NEXT bitPos%
    NEXT bIdx%
NEXT y%

CLOSE #fileNum%
LOCATE 1, 1: PRINT "Done. Press any key...";
WHILE INKEY$ = "": WEND
SCREEN 0: WIDTH 80: CLS
END
`;
  }

  // 2-Bit Loader (CGA 4 colors)
  if (bitDepth === 2) {
    const bytesPerLine = Math.ceil(width / 4);
    return `' ===============================================================
' QBasic 1.1 / QuickBASIC 4.5 - 2-Bit CGA Binary Image Loader
' Image: ${width}x${height} (4 pixels packed per byte)
' Header Mode: ${headerMode.toUpperCase()}
' ===============================================================
DEFINT A-Z
SCREEN 1                    ' 320x200 CGA 4 Colors
COLOR 0, 1                  ' Palette 1 (Black, Cyan, Magenta, White)
CLS

fileName$ = "${fn}"
fileNum% = FREEFILE
OPEN fileName$ FOR BINARY AS #fileNum%

${headerMode === 'qb-header' ? `' Read 8-byte header
magic$ = SPACE$(2)
GET #fileNum%, , magic$
GET #fileNum%, , imgWidth%
GET #fileNum%, , imgHeight%
GET #fileNum%, , bpp$
GET #fileNum%, , flags$
` : ''}imgW% = ${width}
imgH% = ${height}
bytesPerLine% = ${bytesPerLine}

rawByte$ = " "

FOR y% = 0 TO imgH% - 1
    FOR bIdx% = 0 TO bytesPerLine% - 1
        GET #fileNum%, , rawByte$
        b% = ASC(rawByte$)

        ' Unpack 4 pixels (2 bits each: bits 7..6, 5..4, 3..2, 1..0)
        c0% = (b% \ 64) AND 3
        c1% = (b% \ 16) AND 3
        c2% = (b% \ 4) AND 3
        c3% = b% AND 3

        xBase% = bIdx% * 4
        IF xBase% < imgW% THEN PSET (xBase%, y%), c0%
        IF xBase% + 1 < imgW% THEN PSET (xBase% + 1, y%), c1%
        IF xBase% + 2 < imgW% THEN PSET (xBase% + 2, y%), c2%
        IF xBase% + 3 < imgW% THEN PSET (xBase% + 3, y%), c3%
    NEXT bIdx%
NEXT y%

CLOSE #fileNum%
LOCATE 1, 1: PRINT "Press any key to exit...";
WHILE INKEY$ = "": WEND
SCREEN 0: WIDTH 80: CLS
END
`;
  }

  // 3-Bit Loader (8 colors)
  if (bitDepth === 3) {
    const bytesPerLine = Math.ceil(width / 2);
    return `' ===============================================================
' QBasic 1.1 / QuickBASIC 4.5 - 3-Bit Binary Image Loader
' Image: ${width}x${height} 8 Colors (2 pixels packed per byte)
' ===============================================================
DEFINT A-Z
SCREEN 13                   ' 320x200 mode or SCREEN 7
CLS

fileName$ = "${fn}"
fileNum% = FREEFILE
OPEN fileName$ FOR BINARY AS #fileNum%

${headerMode === 'qb-header' ? `' Read header
magic$ = SPACE$(2): GET #fileNum%, , magic$
GET #fileNum%, , imgW%: GET #fileNum%, , imgH%
dummy$ = SPACE$(2): GET #fileNum%, , dummy$
` : `imgW% = ${width}
imgH% = ${height}
`}bytesPerLine% = ${bytesPerLine}
rawByte$ = " "

FOR y% = 0 TO imgH% - 1
    FOR bIdx% = 0 TO bytesPerLine% - 1
        GET #fileNum%, , rawByte$
        b% = ASC(rawByte$)

        c0% = b% AND 7            ' Low 3 bits
        c1% = (b% \ 16) AND 7     ' Upper 3 bits

        xBase% = bIdx% * 2
        IF xBase% < imgW% THEN PSET (xBase%, y%), c0%
        IF xBase% + 1 < imgW% THEN PSET (xBase% + 1, y%), c1%
    NEXT bIdx%
NEXT y%

CLOSE #fileNum%
LOCATE 1, 1: PRINT "Done. Press any key...";
WHILE INKEY$ = "": WEND
SCREEN 0: CLS: END
`;
  }

  // 4-Bit Loader (16 colors EGA/VGA)
  if (bitDepth === 4) {
    const bytesPerLine = Math.ceil(width / 2);
    const screenMode = width > 320 ? 'SCREEN 12' : 'SCREEN 7';
    return `' ===============================================================
' QBasic 1.1 / QuickBASIC 4.5 - 4-Bit (16 Colors) Binary Image Loader
' Screen: ${screenMode} (${width}x${height})
' 2 pixels packed per byte (High nibble = Pixel 0, Low nibble = Pixel 1)
' ===============================================================
DEFINT A-Z
${screenMode}
CLS

fileName$ = "${fn}"
fileNum% = FREEFILE
OPEN fileName$ FOR BINARY AS #fileNum%

${headerMode === 'qb-header' ? `' Read 8-byte structured header
magic$ = SPACE$(2): GET #fileNum%, , magic$
GET #fileNum%, , imgW%: GET #fileNum%, , imgH%
bpp$ = " ": GET #fileNum%, , bpp$
flags$ = " ": GET #fileNum%, , flags$
` : `imgW% = ${width}
imgH% = ${height}
`}bytesPerLine% = ${bytesPerLine}
rawByte$ = " "

FOR y% = 0 TO imgH% - 1
    FOR bIdx% = 0 TO bytesPerLine% - 1
        GET #fileNum%, , rawByte$
        b% = ASC(rawByte$)

        ' High nibble = Left pixel, Low nibble = Right pixel
        c0% = (b% \ 16) AND 15
        c1% = b% AND 15

        xBase% = bIdx% * 2
        IF xBase% < imgW% THEN PSET (xBase%, y%), c0%
        IF xBase% + 1 < imgW% THEN PSET (xBase% + 1, y%), c1%
    NEXT bIdx%
NEXT y%

CLOSE #fileNum%
LOCATE 1, 1: PRINT "Complete. Press any key...";
WHILE INKEY$ = "": WEND
SCREEN 0: CLS: END
`;
  }

  // 6-Bit Loader (64 colors)
  if (bitDepth === 6) {
    return `' ===============================================================
' QBasic 1.1 / QuickBASIC 4.5 - 6-Bit (64 Colors) Binary Image Loader
' 1 byte per pixel (Values 0..63)
' ===============================================================
DEFINT A-Z
SCREEN 13                   ' 320x200 256 colors
CLS

' Setup EGA 64 colors in VGA DAC (Colors 0 to 63)
FOR r% = 0 TO 3
    FOR g% = 0 TO 3
        FOR b% = 0 TO 3
            idx% = (r% * 16) + (g% * 4) + b%
            OUT &H3C8, idx%
            OUT &H3C9, r% * 21      ' 0, 21, 42, 63 (VGA DAC 6-bit levels)
            OUT &H3C9, g% * 21
            OUT &H3C9, b% * 21
        NEXT b%
    NEXT g%
NEXT r%

fileName$ = "${fn}"
fileNum% = FREEFILE
OPEN fileName$ FOR BINARY AS #fileNum%

${headerMode === 'qb-header' ? `dummy$ = SPACE$(8): GET #fileNum%, , dummy$
` : ''}imgW% = ${width}
imgH% = ${height}
rowBuffer$ = SPACE$(imgW%)

FOR y% = 0 TO imgH% - 1
    GET #fileNum%, , rowBuffer$
    FOR x% = 0 TO imgW% - 1
        col% = ASC(MID$(rowBuffer$, x% + 1, 1)) AND 63
        PSET (x%, y%), col%
    NEXT x%
NEXT y%

CLOSE #fileNum%
LOCATE 1, 1: PRINT "Press any key...";
WHILE INKEY$ = "": WEND
SCREEN 0: CLS: END
`;
  }

  // 8-Bit Loader (SCREEN 13 256 Colors)
  if (bitDepth === 8) {
    const hasPal = result.paletteSizeBytes > 0;
    return `' ===============================================================
' QBasic 1.1 / QuickBASIC 4.5 - High-Speed 8-Bit VGA Image Loader
' Resolution: ${width}x${height}, 256 Colors (SCREEN 13)
' Header Mode: ${headerMode.toUpperCase()}
' ===============================================================
DEFINT A-Z
SCREEN 13                   ' 320x200 256 colors VGA mode
CLS

fileName$ = "${fn}"
fileNum% = FREEFILE
OPEN fileName$ FOR BINARY AS #fileNum%

${headerMode === 'qb-header' ? `' Read 8-byte header
magic$ = SPACE$(2): GET #fileNum%, , magic$
IF magic$ <> "QB" THEN PRINT "Invalid QB format!": CLOSE: END
GET #fileNum%, , imgW%
GET #fileNum%, , imgH%
dummy$ = SPACE$(2): GET #fileNum%, , dummy$
` : `imgW% = ${width}
imgH% = ${height}
`}${hasPal ? `' Load 768-byte custom VGA palette directly into DAC hardware registers
palByte$ = " "
FOR c% = 0 TO 255
    GET #fileNum%, , palByte$: rVal% = ASC(palByte$)
    GET #fileNum%, , palByte$: gVal% = ASC(palByte$)
    GET #fileNum%, , palByte$: bVal% = ASC(palByte$)
    OUT &H3C8, c%           ' Set DAC index
    OUT &H3C9, rVal%        ' Red (0..63)
    OUT &H3C9, gVal%        ' Green (0..63)
    OUT &H3C9, bVal%        ' Blue (0..63)
NEXT c%
` : ''}' Ultra-fast row streaming into screen
rowBuffer$ = SPACE$(imgW%)

${width === 320 && height === 200 ? `' Full-screen direct video memory transfer (&HA000)
DEF SEG = &HA000
offset& = 0
FOR y% = 0 TO imgH% - 1
    GET #fileNum%, , rowBuffer$
    FOR x% = 0 TO imgW% - 1
        POKE offset&, ASC(MID$(rowBuffer$, x% + 1, 1))
        offset& = offset& + 1
    NEXT x%
NEXT y%
DEF SEG
` : `FOR y% = 0 TO imgH% - 1
    GET #fileNum%, , rowBuffer$
    FOR x% = 0 TO imgW% - 1
        col% = ASC(MID$(rowBuffer$, x% + 1, 1))
        PSET (x%, y%), col%
    NEXT x%
NEXT y%
`}
CLOSE #fileNum%
LOCATE 1, 1: PRINT "Image loaded. Press any key...";
WHILE INKEY$ = "": WEND
SCREEN 0: WIDTH 80: CLS
END
`;
  }

  // 16-Bit Loader (RGB 5:6:5)
  if (bitDepth === 16) {
    return `' ===============================================================
' QB64 / QBasic - 16-Bit HighColor (RGB 5:6:5) Binary Image Loader
' Reads 2 bytes per pixel (INTEGER) and decodes Red, Green, Blue
' ===============================================================
$RESIZE:SMOOTH
imgW& = ${width}
imgH& = ${height}

' Create 32-bit canvas in modern QB64
screenCanvas& = _NEWIMAGE(imgW&, imgH&, 32)
SCREEN screenCanvas&

fileName$ = "${fn}"
fileNum% = FREEFILE
OPEN fileName$ FOR BINARY AS #fileNum%

${headerMode === 'qb-header' ? `' Skip 8-byte header
dummy$ = SPACE$(8): GET #fileNum%, , dummy$
` : ''}DIM px AS _UNSIGNED _INTEGER

FOR y& = 0 TO imgH& - 1
    FOR x& = 0 TO imgW& - 1
        GET #fileNum%, , px
        ' Extract RGB 5:6:5 channels
        r5% = _SHR(px, 11) AND 31
        g6% = _SHR(px, 5) AND 63
        b5% = px AND 31
        
        ' Scale to 0..255 for display
        r% = (r5% * 255) \ 31
        g% = (g6% * 255) \ 63
        b% = (b5% * 255) \ 31

        PSET (x&, y&), _RGB32(r%, g%, b%)
    NEXT x&
NEXT y&

CLOSE #fileNum%
_TITLE "16-Bit Binary Loader Complete"
DO: _LIMIT 30: LOOP UNTIL INKEY$ <> ""
SYSTEM
`;
  }

  // 24-Bit / 32-Bit Loader
  return `' ===============================================================
' QB64 - ${bitDepth}-Bit TrueColor Binary Image Loader
' Reads raw ${bitDepth === 24 ? 'BGR' : 'BGRA'} pixel stream
' ===============================================================
$RESIZE:SMOOTH
imgW& = ${width}
imgH& = ${height}

screenCanvas& = _NEWIMAGE(imgW&, imgH&, 32)
SCREEN screenCanvas&

fileName$ = "${fn}"
fileNum% = FREEFILE
OPEN fileName$ FOR BINARY AS #fileNum%

${headerMode === 'qb-header' ? `' Skip 8-byte header
dummy$ = SPACE$(8): GET #fileNum%, , dummy$
` : ''}b$ = " ": g$ = " ": r$ = " ": a$ = " "

FOR y& = 0 TO imgH& - 1
    FOR x& = 0 TO imgW& - 1
        GET #fileNum%, , b$
        GET #fileNum%, , g$
        GET #fileNum%, , r$
        ${bitDepth === 32 ? 'GET #fileNum%, , a$' : ''}
        PSET (x&, y&), _RGB32(ASC(r$), ASC(g$), ASC(b$))
    NEXT x&
NEXT y&

CLOSE #fileNum%
_TITLE "${bitDepth}-Bit TrueColor Display"
DO: _LIMIT 30: LOOP UNTIL INKEY$ <> ""
SYSTEM
`;
}

export function generateQBasicSaverCode(options: CodeGeneratorOptions): string {
  const { filename, result } = options;
  const { width, height, bitDepth, headerMode } = result;

  const fn = filename.toUpperCase().endsWith('.BIN') ? filename.toUpperCase() : `${filename.toUpperCase()}.BIN`;

  if (bitDepth === 1) {
    const bytesPerLine = Math.ceil(width / 8);
    return `' ===============================================================
' QBasic 1.1 / QuickBASIC 4.5 - 1-Bit Binary Image Screen Saver
' Captures the active SCREEN and packs 8 pixels per byte into binary
' ===============================================================
DEFINT A-Z
saveFile$ = "${fn}"
fileNum% = FREEFILE

OPEN saveFile$ FOR BINARY AS #fileNum%

${headerMode === 'qb-header' ? `' Write 8-byte header
magic$ = "QB"
PUT #fileNum%, , magic$
w% = ${width}: PUT #fileNum%, , w%
h% = ${height}: PUT #fileNum%, , h%
bpp$ = CHR$(1): PUT #fileNum%, , bpp$
flags$ = CHR$(0): PUT #fileNum%, , flags$
` : ''}imgW% = ${width}
imgH% = ${height}
bytesPerLine% = ${bytesPerLine}

PRINT "Saving 1-bit screen to "; saveFile$; "..."

FOR y% = 0 TO imgH% - 1
    FOR bIdx% = 0 TO bytesPerLine% - 1
        byteVal% = 0
        FOR bitPos% = 7 TO 0 STEP -1
            x% = bIdx% * 8 + (7 - bitPos%)
            IF x% < imgW% THEN
                IF POINT(x%, y%) <> 0 THEN
                    byteVal% = byteVal% OR (2 ^ bitPos%)
                END IF
            END IF
        NEXT bitPos%
        outCh$ = CHR$(byteVal%)
        PUT #fileNum%, , outCh$
    NEXT bIdx%
NEXT y%

CLOSE #fileNum%
PRINT "Saved successfully!"
`;
  }

  if (bitDepth === 4) {
    const bytesPerLine = Math.ceil(width / 2);
    return `' ===============================================================
' QBasic 1.1 / QuickBASIC 4.5 - 4-Bit (16 Colors) Image Saver
' Captures SCREEN 7 / SCREEN 12 pixels and packs 2 pixels per byte
' ===============================================================
DEFINT A-Z
saveFile$ = "${fn}"
fileNum% = FREEFILE

OPEN saveFile$ FOR BINARY AS #fileNum%

${headerMode === 'qb-header' ? `' Write 8-byte header
magic$ = "QB": PUT #fileNum%, , magic$
w% = ${width}: PUT #fileNum%, , w%
h% = ${height}: PUT #fileNum%, , h%
bpp$ = CHR$(4): PUT #fileNum%, , bpp$
flags$ = CHR$(0): PUT #fileNum%, , flags$
` : ''}imgW% = ${width}
imgH% = ${height}
bytesPerLine% = ${bytesPerLine}

FOR y% = 0 TO imgH% - 1
    FOR bIdx% = 0 TO bytesPerLine% - 1
        xBase% = bIdx% * 2
        p0% = POINT(xBase%, y%) AND 15
        p1% = 0
        IF xBase% + 1 < imgW% THEN p1% = POINT(xBase% + 1, y%) AND 15

        packedByte% = (p0% * 16) OR p1%
        outCh$ = CHR$(packedByte%)
        PUT #fileNum%, , outCh$
    NEXT bIdx%
NEXT y%

CLOSE #fileNum%
PRINT "4-bit binary file saved successfully!"
`;
  }

  if (bitDepth === 8) {
    return `' ===============================================================
' QBasic 1.1 / QuickBASIC 4.5 - 8-Bit (SCREEN 13) Binary Saver
' Reads pixels from VGA Screen 13 and dumps raw binary data
' ===============================================================
DEFINT A-Z
saveFile$ = "${fn}"
fileNum% = FREEFILE

OPEN saveFile$ FOR BINARY AS #fileNum%

${headerMode === 'qb-header' ? `' Write 8-byte header
magic$ = "QB": PUT #fileNum%, , magic$
w% = ${width}: PUT #fileNum%, , w%
h% = ${height}: PUT #fileNum%, , h%
bpp$ = CHR$(8): PUT #fileNum%, , bpp$
flags$ = CHR$(0): PUT #fileNum%, , flags$
` : ''}imgW% = ${width}
imgH% = ${height}

PRINT "Saving SCREEN 13 binary..."

' Stream lines from video memory
rowBuffer$ = SPACE$(imgW%)
FOR y% = 0 TO imgH% - 1
    FOR x% = 0 TO imgW% - 1
        c% = POINT(x%, y%)
        MID$(rowBuffer$, x% + 1, 1) = CHR$(c%)
    NEXT x%
    PUT #fileNum%, , rowBuffer$
NEXT y%

CLOSE #fileNum%
PRINT "Done! File saved as "; saveFile$
`;
  }

  // 16-bit / 24-bit / 32-bit Saver (QB64)
  return `' ===============================================================
' QB64 - ${bitDepth}-Bit Image Buffer Saver
' Reads truecolor pixel values and writes binary stream
' ===============================================================
saveFile$ = "${fn}"
fileNum% = FREEFILE
OPEN saveFile$ FOR BINARY AS #fileNum%

${headerMode === 'qb-header' ? `' Write header
magic$ = "QB": PUT #fileNum%, , magic$
w% = ${width}: PUT #fileNum%, , w%
h% = ${height}: PUT #fileNum%, , h%
bpp$ = CHR$(${bitDepth}): PUT #fileNum%, , bpp$
flags$ = CHR$(0): PUT #fileNum%, , flags$
` : ''}imgW& = ${width}
imgH& = ${height}

FOR y& = 0 TO imgH& - 1
    FOR x& = 0 TO imgW& - 1
        col& = POINT(x&, y&)
        r% = _RED32(col&)
        g% = _GREEN32(col&)
        b% = _BLUE32(col&)

        ${bitDepth === 16 ? `' RGB 5:6:5 integer
        px% = (_SHL(r% \\ 8, 11)) OR (_SHL(g% \\ 4, 5)) OR (b% \\ 8)
        PUT #fileNum%, , px%
        ` : bitDepth === 24 ? `bCh$ = CHR$(b%): PUT #fileNum%, , bCh$
        gCh$ = CHR$(g%): PUT #fileNum%, , gCh$
        rCh$ = CHR$(r%): PUT #fileNum%, , rCh$
        ` : `bCh$ = CHR$(b%): PUT #fileNum%, , bCh$
        gCh$ = CHR$(g%): PUT #fileNum%, , gCh$
        rCh$ = CHR$(r%): PUT #fileNum%, , rCh$
        aCh$ = CHR$(255): PUT #fileNum%, , aCh$
        `}
    NEXT x&
NEXT y&

CLOSE #fileNum%
PRINT "Saved ${bitDepth}-bit binary file successfully."
`;
}

// Generate compact DATA statements for embedding sprites directly into QBasic source code
export function generateQBasicDataStatements(result: ConversionResult, maxBytesToExport: number = 512): string {
  const { width, height, bitDepth, binaryData } = result;
  const bytes = binaryData.slice(0, Math.min(binaryData.length, maxBytesToExport));
  const hexLines: string[] = [];

  const bytesPerLine = 16;
  for (let i = 0; i < bytes.length; i += bytesPerLine) {
    const chunk = Array.from(bytes.slice(i, i + bytesPerLine));
    const hexParts = chunk.map(b => `&H${b.toString(16).toUpperCase().padStart(2, '0')}`);
    hexLines.push(`DATA ${hexParts.join(', ')}`);
  }

  return `' ===============================================================
' QBasic Embedded DATA Statements
' Size: ${width}x${height}, ${bitDepth}-Bit (${bytes.length} bytes shown)
' ===============================================================
DEFINT A-Z
SCREEN 13

DIM spriteBuffer%(${Math.ceil(bytes.length / 2)})

RESTORE SpriteData
DEF SEG = VARSEG(spriteBuffer%(0))
offset% = VARPTR(spriteBuffer%(0))

FOR i% = 0 TO ${bytes.length - 1}
    READ byteVal%
    POKE offset% + i%, byteVal%
NEXT i%
DEF SEG

' Blit sprite to screen
PUT (50, 50), spriteBuffer%, PSET

LOCATE 1, 1: PRINT "DATA Sprite loaded!";
WHILE INKEY$ = "": WEND
END

SpriteData:
${hexLines.join('\n')}
${binaryData.length > maxBytesToExport ? `' [Truncated: ${binaryData.length - maxBytesToExport} remaining bytes omitted for brevity]` : ''}
`;
}
